#!/usr/bin/env node
/**
 * Content-hash core head assets and regenerate content/partials/head-assets.html.
 * Replaces hand-managed ?v= pins with sc-theme.<hash8>.css style URLs.
 */
import { createHash } from 'node:crypto';
import {
  readFileSync,
  writeFileSync,
  existsSync,
  readdirSync,
  unlinkSync,
  copyFileSync,
  mkdirSync,
} from 'node:fs';
import { join, dirname, basename, extname } from 'node:path';

const ROOT = process.cwd();

/** Logical name → source path under public/ */
const ASSETS = [
  { id: 'sc-theme.css', src: 'public/sc-theme.css', urlBase: '/sc-theme' },
  { id: 'sc-site-nav.css', src: 'public/sc-site-nav.css', urlBase: '/sc-site-nav' },
  { id: 'sc-calc-sheet.css', src: 'public/sc-calc-sheet.css', urlBase: '/sc-calc-sheet' },
  { id: 'seo-content.css', src: 'public/css/seo-content.css', urlBase: '/css/seo-content' },
  { id: 'sc-theme.js', src: 'public/sc-theme.js', urlBase: '/sc-theme' },
  { id: 'sc-site-nav.js', src: 'public/sc-site-nav.js', urlBase: '/sc-site-nav' },
];

function shortHash(buf) {
  return createHash('sha256').update(buf).digest('hex').slice(0, 8);
}

function cleanStaleHashed(outDir, stem, ext, keepName) {
  if (!existsSync(outDir)) return;
  const re = new RegExp(`^${stem}\\.[a-f0-9]{8}\\${ext}$`);
  for (const name of readdirSync(outDir)) {
    if (!re.test(name)) continue;
    if (name === keepName) continue;
    unlinkSync(join(outDir, name));
  }
}

function main() {
  const manifest = {
    generatedAt: new Date().toISOString(),
    files: {},
  };

  for (const asset of ASSETS) {
    const abs = join(ROOT, asset.src);
    if (!existsSync(abs)) {
      console.error(`[FAIL] missing asset source ${asset.src}`);
      process.exit(1);
    }
    const buf = readFileSync(abs);
    const hash = shortHash(buf);
    const ext = extname(asset.src); // .css / .js
    const stem = basename(asset.urlBase);
    const hashedName = `${stem}.${hash}${ext}`;
    const outDir = dirname(abs);
    const outAbs = join(outDir, hashedName);
    mkdirSync(outDir, { recursive: true });
    copyFileSync(abs, outAbs);
    cleanStaleHashed(outDir, stem, ext, hashedName);

    const url =
      asset.urlBase.includes('/') && asset.urlBase.startsWith('/css/')
        ? `/css/${hashedName}`
        : `/${hashedName}`;
    // urlBase for seo-content is /css/seo-content → /css/seo-content.<hash>.css
    const publicUrl =
      dirname(asset.src) === 'public/css'
        ? `/css/${hashedName}`
        : `/${hashedName}`;

    manifest.files[asset.id] = {
      source: asset.src,
      hash,
      href: publicUrl,
      file: relativeOut(asset.src, hashedName),
    };
    console.log(`[OK] ${asset.id} → ${publicUrl}`);
  }

  const f = manifest.files;
  const partial = `<!-- SSOT: generated by scripts/hash-head-assets.mjs — do not hand-edit hashed hrefs. -->
<link rel="stylesheet" href="${f['sc-theme.css'].href}">
<link rel="stylesheet" href="${f['sc-site-nav.css'].href}">
<link rel="stylesheet" href="${f['sc-calc-sheet.css'].href}">
<link rel="stylesheet" href="${f['seo-content.css'].href}">
<script src="${f['sc-theme.js'].href}" defer></script>
<script src="${f['sc-site-nav.js'].href}" defer></script>
`;

  writeFileSync(join(ROOT, 'content/partials/head-assets.html'), partial, 'utf8');
  mkdirSync(join(ROOT, 'seo'), { recursive: true });
  writeFileSync(join(ROOT, 'seo/asset-manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
  console.log('[PASS] head-assets partial + seo/asset-manifest.json written');
}

function relativeOut(src, hashedName) {
  if (src.startsWith('public/css/')) return `public/css/${hashedName}`;
  return `public/${hashedName}`;
}

main();
